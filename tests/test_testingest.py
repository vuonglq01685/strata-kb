"""`kb report-ingest` — the `<repo_id>-test` document built from tests/ and reports/."""

from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path

import pytest
from typer.testing import CliRunner

from strata_kb import models, testingest
from strata_kb.cli import app
from tests.test_testcases import STORY, _dir, _spec
from tests.test_testreport import _d, _report

SPEC_FILES = ("tc01.spec.ts", "tc02.spec.ts", "tc03.spec.ts")
PNG = b"\x89PNG-evidence"


def write_repo(root: Path, *, spec: str | None = None, report: str | None = None):
    """tests/ST-1/ (spec + scripts) and reports/ST-1/R1.md (+ one evidence PNG)."""
    d = _dir(root, *SPEC_FILES)
    (d / "test-cases.md").write_text(spec or _spec(), encoding="utf-8")
    r = root / "reports" / STORY
    (r / "assets").mkdir(parents=True)
    (r / "assets/tc01.png").write_bytes(PNG)
    (r / "R1.md").write_text(report or _report(), encoding="utf-8")
    (root / "kb").mkdir(exist_ok=True)
    return root


def run_tests(root: Path, children=lambda _s: ()) -> testingest.TestIngestReport:
    return testingest.run(
        root, root / "kb", "shop", root / "tests", root / "reports", children
    )


def doc_file(root: Path, name: str) -> str:
    return (root / "kb" / "shop-test" / name).read_text(encoding="utf-8")


def test_story_group_has_cases_then_rounds(tmp_path):
    write_repo(tmp_path)
    r2 = _report().replace("Round: 1", "Round: 2").replace("# R1", "# R2")
    (tmp_path / "reports" / STORY / "R2.md").write_text(r2, encoding="utf-8")
    rep = run_tests(tmp_path)
    assert rep.published == [f"{STORY}.cases", f"{STORY}.R1", f"{STORY}.R2"]
    assert not rep.skipped
    manifest = models.load_yaml_model(
        tmp_path / "kb/shop-test/_manifest.yaml", models.Manifest
    )
    assert manifest.title == "shop — tests"
    assert [(s.id, s.summary, s.file) for s in manifest.sections] == [
        (f"{STORY}.cases", "3 test cases", STORY),
        (f"{STORY}.R1", "R1 PASS — 1/1", STORY),
        (f"{STORY}.R2", "R2 PASS — 1/1", STORY),
    ]
    assert "Generated by kb report-ingest" in doc_file(tmp_path, f"{STORY}.md")
    assert (tmp_path / f"kb/shop-test/{STORY}.raw.md").is_file()
    index = (tmp_path / "kb/index.yaml").read_text(encoding="utf-8")
    assert "shop-test" in index and "generated" in index


def test_report_skipped_when_cases_fail_lint(tmp_path):
    write_repo(tmp_path)
    (tmp_path / "tests" / STORY / "tc01.spec.ts").unlink()  # script of TC-01
    rep = run_tests(tmp_path)
    assert rep.published == []
    files = [f for f, _ in rep.skipped]
    assert files == [f"tests/{STORY}/test-cases.md", f"reports/{STORY}/R1.md"]
    assert "cases" in rep.skipped[1][1]
    assert not (tmp_path / "kb/shop-test").exists()


def test_images_hashed_into_assets_and_refs_rewritten(tmp_path):
    write_repo(tmp_path)
    run_tests(tmp_path)
    name = f"{hashlib.sha256(PNG).hexdigest()}.png"
    assert doc_file(tmp_path, f"{STORY}.raw.md").count(f"assets/{name}") == 1
    assert "assets/tc01.png" not in doc_file(tmp_path, f"{STORY}.raw.md")
    assert [p.name for p in (tmp_path / "kb/shop-test/assets").iterdir()] == [name]


def test_symlinked_image_skips_report_with_reason(tmp_path):
    write_repo(tmp_path)
    img = tmp_path / "reports" / STORY / "assets/tc01.png"
    outside = tmp_path / "secret.png"
    outside.write_bytes(b"s")
    img.unlink()
    os.symlink(outside, img)
    rep = run_tests(tmp_path)
    assert rep.published == [f"{STORY}.cases"]
    assert "symlink" in rep.skipped[0][1]
    assert not (tmp_path / "kb/shop-test/assets").exists()


def test_output_is_deterministic(tmp_path):
    write_repo(tmp_path)
    run_tests(tmp_path)
    doc = tmp_path / "kb/shop-test"
    first = {p.name: p.read_bytes() for p in doc.rglob("*") if p.is_file()}
    run_tests(tmp_path)
    assert first == {p.name: p.read_bytes() for p in doc.rglob("*") if p.is_file()}


def test_children_fall_back_to_callback_when_header_empty(tmp_path):
    spec = _spec().replace(f"Children: {STORY}.web", "Children: ")
    write_repo(tmp_path, spec=spec, report=_report(defects=_defect_for("ST-1.web")))
    asked: list[str] = []

    def kids(story: str):
        asked.append(story)
        return ("ST-1.web",)

    run_tests(tmp_path, kids)
    assert asked == [STORY]


def _defect_for(guilty: str) -> str:
    return _d(1, guilty)


def test_foreign_document_is_refused(tmp_path):
    write_repo(tmp_path)
    doc = tmp_path / "kb/shop-test"
    doc.mkdir()
    (doc / "_manifest.yaml").write_text(
        "id: shop-test\ntitle: hand written\nrevision: ''\nsource_sha256: ''\n"
        "ingested: 2026-01-01\nsections: []\n",
        encoding="utf-8",
    )
    with pytest.raises(testingest.TestIngestError, match="did not generate"):
        run_tests(tmp_path)


def test_cli_report_ingest_json(tmp_path):
    write_repo(tmp_path)
    result = CliRunner().invoke(
        app,
        ["report-ingest", "--repo-root", str(tmp_path), "--kb-dir", str(tmp_path / "kb"),
         "--repo-id", "shop", "--tests-dir", str(tmp_path / "tests"),
         "--reports-dir", str(tmp_path / "reports"), "--json"],
    )  # fmt: skip
    assert result.exit_code == 0, result.output
    assert json.loads(result.stdout)["published"] == [f"{STORY}.cases", f"{STORY}.R1"]
