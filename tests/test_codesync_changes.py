from __future__ import annotations

from pathlib import Path

import pytest

from strata_kb import gitio, models
from strata_kb.codesync.changes import code_changes

BANNER = "> Generated by kb code-ingest at {sha} — do not edit by hand."


def _svc(depends: str, image: str = "acme/pay:1.0") -> str:
    return (
        "| Property | Value |\n| --- | --- |\n"
        f"| Image | `{image}` |\n| Source | docker-compose.yml |\n"
        f"| Depends on | {depends} |\n| Ports | 8080:8080 |\n"
        "| Env keys | PAY_DB |\n| Technology | FastAPI |\n"
    )


def _db(*cols: str) -> str:
    rows = "".join(f"| {c} | TEXT |  |\n" for c in cols)
    return f"| Column | Type | PK |\n| --- | --- | --- |\n| id | BIGINT | yes |\n{rows}"


STRIPE = "| Env key | Purpose |\n| --- | --- |\n| STRIPE_KEY | auth |\n"

BASE_SECTIONS = {
    "svc.payment": ("payment", _svc("`ledger`, `postgres`")),
    "svc.ledger": ("ledger", _svc("`postgres`")),
    "db.payments": ("payments", _db("amount")),
    "int.stripe": ("stripe", STRIPE),
}

# BASE_SECTIONS with the payment service named like hub prose names it
# (`payment-service`): a bare "payment" would also hit a "Payment flow" heading.
SCAN_SECTIONS = {
    **{k: v for k, v in BASE_SECTIONS.items() if k != "svc.payment"},
    "svc.payment-service": ("payment-service", _svc("`ledger`, `postgres`")),
}


def write_doc(
    hub: Path,
    repo: str,
    kind: str,
    sections: dict[str, tuple[str, str]],
    *,
    sha: str = "aaa1111",
    spacer: str = "",
) -> None:
    """One-file federation doc shaped like the renderer's: banner under the
    title, `## <id> <title>` sections, a `.raw.md` twin (make_fed_entry only
    writes one section and refuses an existing dir)."""
    doc_id = f"{repo}-{kind}"
    doc = hub / "federation" / repo / doc_id
    doc.mkdir(parents=True, exist_ok=True)
    banner = BANNER.format(sha=sha)
    head = f"# {doc_id}\n\n{banner}\n\n"
    body = "".join(
        f"## {sid} {title}\n\n{spacer}{text}\n"
        for sid, (title, text) in sections.items()
    )
    (doc / "ch1.md").write_text(head + body, encoding="utf-8")
    (doc / "ch1.raw.md").write_text(head + body, encoding="utf-8")
    models.save_yaml_model(
        doc / "_manifest.yaml",
        models.Manifest(
            id=doc_id,
            title=f"{repo} — {kind} knowledge",
            sections=[
                models.SectionEntry(
                    id=sid, title=title, summary="s", status="summarized", file="ch1"
                )
                for sid, (title, _) in sections.items()
            ],
        ),
    )


def write_svc(hub: Path, prose: str, *, sha: str = "aaa1111") -> None:
    # Banner inside the section: facts_for must strip it from the text fact.
    text = f"{BANNER.format(sha=sha)}\n\n{prose}"
    write_doc(hub, "acme", "svc", {"flow.checkout": ("Checkout", text)}, sha=sha)


def commit(root: Path, run_git) -> str:
    run_git(root, "add", "-A")
    run_git(root, "commit", "-m", "c")
    return run_git(root, "rev-parse", "HEAD")


@pytest.fixture
def hub(tmp_path: Path, run_git):
    root = tmp_path / "hub"
    root.mkdir()
    run_git(root, "init")
    write_doc(root, "acme", "code", BASE_SECTIONS)
    write_svc(root, "Checkout calls the ledger service.")
    return root, commit(root, run_git)


def test_removed_dependency_is_one_changed_item(hub, run_git):
    root, c1 = hub
    sections = {**BASE_SECTIONS, "svc.payment": ("payment", _svc("`postgres`"))}
    write_doc(root, "acme", "code", sections)
    [item] = code_changes(root, c1, commit(root, run_git))
    assert (item.repo_id, item.doc_id, item.section_id) == (
        "acme",
        "acme-code",
        "svc.payment",
    )
    assert item.title == "payment"
    assert item.status == "changed"
    assert item.removed == {("depends_on", "ledger")}
    assert item.added == frozenset()


def test_banner_image_and_reformat_only_changes_yield_nothing(hub, run_git):
    root, c1 = hub
    sections = {
        **BASE_SECTIONS,
        "svc.payment": ("payment", _svc("`ledger`, `postgres`", "acme/pay:9.9")),
    }
    write_doc(root, "acme", "code", sections, sha="bbb2222", spacer="\n\n")
    write_svc(root, "Checkout calls\nthe   ledger service.", sha="bbb2222")
    assert code_changes(root, c1, commit(root, run_git)) == []


def test_added_and_removed_sections(hub, run_git):
    root, c1 = hub
    sections = {k: v for k, v in BASE_SECTIONS.items() if k != "int.stripe"}
    sections["db.refunds"] = ("refunds", _db("reason"))
    write_doc(root, "acme", "code", sections)
    refunds, stripe = code_changes(root, c1, commit(root, run_git))
    assert (refunds.section_id, refunds.status, refunds.title) == (
        "db.refunds",
        "added",
        "refunds",
    )
    assert ("column", "reason") in refunds.added and refunds.removed == frozenset()
    assert (stripe.section_id, stripe.status, stripe.title) == (
        "int.stripe",
        "removed",
        "stripe",
    )
    assert stripe.removed == {("env_key", "STRIPE_KEY")}
    assert stripe.added == frozenset()


def test_new_dev_repo_is_one_doc_level_item(hub, run_git):
    root, c1 = hub
    write_doc(root, "zeta", "code", {"int.kafka": ("kafka", STRIPE)})
    c2 = commit(root, run_git)
    [item] = code_changes(root, c1, c2)
    assert (item.repo_id, item.doc_id) == ("zeta", "zeta-code")
    assert item.section_id is None and item.status == "added"
    assert item.title == "zeta — code knowledge"
    assert item.added == {("env_key", "STRIPE_KEY")}
    [gone] = code_changes(root, c2, c1)
    assert gone.section_id is None and gone.status == "removed"
    assert gone.removed == item.added and gone.added == frozenset()


def test_svc_flow_text_change_is_changed(hub, run_git):
    root, c1 = hub
    write_svc(root, "Checkout calls the ledger and the fraud service.")
    [item] = code_changes(root, c1, commit(root, run_git))
    assert (item.doc_id, item.section_id, item.status) == (
        "acme-svc",
        "flow.checkout",
        "changed",
    )
    assert {k for k, _ in item.added} == {"text"} == {k for k, _ in item.removed}


def test_reads_git_objects_not_worktree(hub, run_git):
    root, c1 = hub
    sections = {**BASE_SECTIONS, "svc.payment": ("payment", _svc("`postgres`"))}
    write_doc(root, "acme", "code", sections)
    c2 = commit(root, run_git)
    expected = code_changes(root, c1, c2)
    write_doc(root, "acme", "code", {"db.other": ("other", _db("x"))})
    (root / "federation" / "acme" / "acme-svc" / "_manifest.yaml").unlink()
    assert code_changes(root, c1, c2) == expected


def test_results_sorted_and_deterministic(hub, run_git):
    root, c1 = hub
    sections = {
        **BASE_SECTIONS,
        "svc.payment": ("payment", _svc("`postgres`")),
        "db.payments": ("payments", _db("amount", "currency")),
    }
    write_doc(root, "acme", "code", sections)
    write_svc(root, "Totally different prose.")
    c2 = commit(root, run_git)
    items = code_changes(root, c1, c2)
    assert [(i.doc_id, i.section_id) for i in items] == [
        ("acme-code", "db.payments"),
        ("acme-code", "svc.payment"),
        ("acme-svc", "flow.checkout"),
    ]
    assert code_changes(root, c1, c2) == items


def test_missing_base_raises_git_error(hub):
    root, c1 = hub
    with pytest.raises(gitio.GitError):
        code_changes(root, "0" * 40, c1)


def test_added_in_scope_section_without_facts_is_still_one_item(hub, run_git):
    root, c1 = hub
    sections = {
        **BASE_SECTIONS,
        "cmd.deploy": ("Deploy command", "No primary command."),
    }
    write_doc(root, "acme", "code", sections)
    c2 = commit(root, run_git)
    [item] = code_changes(root, c1, c2)
    assert (item.section_id, item.status, item.title) == (
        "cmd.deploy",
        "added",
        "Deploy command",
    )
    assert item.added == frozenset() == item.removed
    [gone] = code_changes(root, c2, c1)
    assert (gone.section_id, gone.status) == ("cmd.deploy", "removed")


